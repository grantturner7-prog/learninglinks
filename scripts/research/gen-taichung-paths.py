"""Writes src/components/home/taichung-paths.ts: a small, decorative outline of Taichung's districts for the home page."""
import json, math
R = "docs/demo/"  # run from the repository root: python3 scripts/research/gen-taichung-paths.py
T = json.load(open(R + "taiwan-districts.json"))
arcs = []
for a in T["arcs"]:
    pts = [(a[0], a[1])]
    for i in range(2, len(a), 2):
        pts.append((pts[-1][0] + a[i], pts[-1][1] + a[i + 1]))
    arcs.append(pts)

def ring(idx):
    pts = []
    for i in idx:
        seg = arcs[i] if i >= 0 else list(reversed(arcs[~i]))
        pts += seg if not pts else seg[1:]
    return pts

D = {d[0]: {"en": d[1], "zh": d[2], "x": d[3], "y": d[4], "polys": d[6]} for d in T["d"]}
counts = {"taichung:xitun": 6, "taichung:nantun": 5, "taichung:beitun": 4, "taichung:west": 3, "taichung:north": 2, "taichung:taiping": 2,
          "taichung:fengyuan": 3, "taichung:dali": 2, "taichung:shalu": 1, "taichung:wuri": 1, "taichung:tanzi": 1}
xs = [D[k]["x"] for k in counts]; ys = [D[k]["y"] for k in counts]
x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
mx = (x1 - x0) * 0.42; my = (y1 - y0) * 0.34
x0 -= mx; x1 += mx; y0 -= my; y1 += my
VW = 900; sc = VW / (x1 - x0); VH = round((y1 - y0) * sc)
P = lambda p: ((p[0] - x0) * sc, (p[1] - y0) * sc)

def simplify(pts, tol):
    out = [pts[0]]
    for p in pts[1:-1]:
        if math.hypot(p[0] - out[-1][0], p[1] - out[-1][1]) >= tol:
            out.append(p)
    out.append(pts[-1]); return out

def dpath(polys, tol):
    s = []
    for poly in polys:
        for r in poly:
            pts = simplify([P(p) for p in ring(r)], tol)
            if len(pts) < 4: continue
            s.append("M" + "L".join(f"{round(x)} {round(y)}" for x, y in pts) + "Z")
    return "".join(s)

def near(d):
    x, y = P((d["x"], d["y"])); return -260 < x < VW + 260 and -260 < y < VH + 260

rows = []; labels = []
for k, d in D.items():
    if not near(d): continue
    tc = k.startswith("taichung:")
    rows.append((k, dpath(d["polys"], 2.2 if tc else 4.0), counts.get(k, 0) if tc else -1))
    x, y = P((d["x"], d["y"]))
    if tc and k in counts:
        labels.append((k, d["en"], d["zh"], round(x), round(y), counts[k]))
out = ['/**', ' * Outlines of the districts in and around Taichung City, simplified from the Ministry of the Interior open data.',
       ' * Decorative only: used by the SAMPLE district picture on the home page. The counts are made up; it is not data',
       ' * about people and it is not the interactive map (that is src/components/map).',
       ' * Generated by scripts/research/gen-taichung-paths.py; do not edit by hand.', ' */',
       f'export const TAICHUNG_VIEWBOX = "0 0 {VW} {VH}";', '',
       '/** [area key, outline, made-up count (0 = none, -1 = a neighbouring county)] */',
       'export const TAICHUNG_PATHS: ReadonlyArray<readonly [key: string, d: string, n: number]> = [']
for k, d, n in rows:
    out.append(f'  ["{k}", "{d}", {n}],')
out += ['];', '', '/** [area key, English name, Chinese name, x, y, made-up count] for the districts that carry a bubble. */',
        'export const TAICHUNG_LABELS: ReadonlyArray<readonly [key: string, en: string, zh: string, x: number, y: number, n: number]> = [']
for l in labels:
    out.append(f'  ["{l[0]}", "{l[1]}", "{l[2]}", {l[3]}, {l[4]}, {l[5]}],')
out.append('];')
open("src/components/home/taichung-paths.ts", "w", encoding="utf-8").write("\n".join(out) + "\n")
print("viewBox", VW, VH, "areas", len(rows), "labels", labels)
